/** OBD-II Mode 01 PID database (SAE J1979) — 1:1 port of the web dashboard's obd.ts. */
data class PidDef(
    val pid: Int,
    val name: String,
    val unit: String,
    val bytes: Int,
    val min: Double,
    val max: Double,
    val decode: (ByteArray) -> Double,
)

private fun u8(d: ByteArray, i: Int) = d[i].toInt() and 0xFF
private fun u16(d: ByteArray) = (u8(d, 0) shl 8) or u8(d, 1)
private fun s16(d: ByteArray): Int {
    val v = u16(d); return if (v and 0x8000 != 0) v - 65536 else v
}
private fun pct(d: ByteArray) = u8(d, 0) / 2.55
private fun trim(d: ByteArray) = u8(d, 0) / 1.28 - 100
private fun temp(d: ByteArray) = u8(d, 0) - 40.0

